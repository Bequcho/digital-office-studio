-- BEQSON Lead CRM v1
-- Prepared for Supabase/PostgreSQL. Public website submissions should enter through
-- a server-side Edge Function; do not expose service-role credentials in GitHub Pages.

create extension if not exists pgcrypto;

create table if not exists public.leads (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  name text not null,
  contact text not null,
  industry text,
  budget text,
  website text,
  message text not null,
  language text not null default 'en',
  page_url text,
  page_path text,
  page_title text,
  referrer text,
  first_source text,
  utm_source text,
  utm_medium text,
  utm_campaign text,
  status text not null default 'new' check (status in ('new','contacted','proposal','won','in_progress','done','lost')),
  lead_score integer check (lead_score between 0 and 100),
  ai_summary text,
  recommended_package text,
  internal_notes text
);

create table if not exists public.lead_events (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  lead_id uuid references public.leads(id) on delete cascade,
  event_type text not null,
  event_data jsonb not null default '{}'::jsonb
);

create index if not exists leads_created_at_idx on public.leads(created_at desc);
create index if not exists leads_status_idx on public.leads(status);
create index if not exists leads_source_idx on public.leads(first_source);
create index if not exists lead_events_lead_id_idx on public.lead_events(lead_id, created_at desc);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists leads_set_updated_at on public.leads;
create trigger leads_set_updated_at
before update on public.leads
for each row execute function public.set_updated_at();

alter table public.leads enable row level security;
alter table public.lead_events enable row level security;

-- Intentionally no anonymous INSERT/SELECT policies here.
-- The public site will submit to a Supabase Edge Function with validation/rate limiting.
-- The CRM dashboard will use authenticated access with explicit policies.